#!/usr/bin/env python3
"""Translate the pinned symbols! data; the original Rust macro is the oracle.

Only the macro input's supported grammar is accepted. This is a source-aligned
data generator, not an implementation of the rustc_macros crate or Rust parser.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import native_profile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".toolchain/upstream-rust/compiler/rustc_span/src/symbol.rs"
SOURCE_SHA256 = "d623770418e98bafe1190ab29635127bf51736684b732531b280c657f4825973"
TARGET = ROOT / "port/rust/compiler/rustc_span/src/symbol_predefined.go"


def rust_string(text):
    assert text[0] == text[-1] == '"'
    result, i = [], 1
    escapes = {'n': '\n', 'r': '\r', 't': '\t', '0': '\0', '\\': '\\', '"': '"', "'": "'"}
    while i < len(text) - 1:
        if text[i] != '\\':
            result.append(text[i]); i += 1; continue
        i += 1
        if text[i] in escapes:
            result.append(escapes[text[i]]); i += 1
        elif text[i] == '\n':
            i += 1
            while i < len(text) and text[i].isspace(): i += 1
        elif text.startswith('u{', i):
            end = text.index('}', i + 2)
            result.append(chr(int(text[i + 2:end].replace('_', ''), 16))); i = end + 1
        elif text[i] == 'x':
            result.append(chr(int(text[i + 1:i + 3], 16))); i += 3
        else:
            raise ValueError(f"unsupported Rust string escape: {text[i:]}")
    return ''.join(result)


def invocation(source):
    start = source.index('symbols! {')
    # Lex strings/comments before punctuation so braces and commas inside values
    # cannot change the macro grammar.
    pattern = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z_0-9]*|\S', re.S)
    tokens = [m.group() for m in pattern.finditer(source, start) if not m.group().startswith(('//', '/*'))]
    pos = 0

    def take(expected=None):
        nonlocal pos
        value = tokens[pos]; pos += 1
        if expected is not None and value != expected:
            raise ValueError(f"expected {expected!r}, found {value!r}")
        return value

    take('symbols'); take('!'); take('{')
    groups = []
    for group in ('Keywords', 'Symbols'):
        take(group); take('{'); entries = []
        while tokens[pos] != '}':
            name = take()
            if re.fullmatch('[A-Za-z_][A-Za-z_0-9]*', name) is None:
                raise ValueError(f"unsupported identifier: {name}")
            kind, value = 'string', name
            if tokens[pos] == ':':
                take(':'); value = take()
                if value.startswith('"'): value = rust_string(value)
                elif value == 'env':
                    take('!'); take('('); value = rust_string(take()); take(')'); kind = 'env'
                else: raise ValueError(f"unsupported expression for symbol {name}: {value}")
            elif group == 'Keywords': raise ValueError(f"keyword {name} needs a string")
            entries.append((name, kind, value))
            take(',')
        take('}'); groups.append(entries)
    take('}')
    return groups


def definitions(source, release):
    keywords, symbols = invocation(source)
    values, indices, named = [], {}, []

    def insert(value):
        if value in indices: raise ValueError(f"Symbol `{value}` is duplicated")
        index = len(values); indices[value] = index; values.append(value)
        return index

    for group, entries in (('kw', keywords), ('sym', symbols)):
        for name, kind, value in entries:
            if kind != 'env': named.append((group, name, insert(value)))
    bases = []
    for sequence in ('0123456789', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'):
        bases.append(len(values))
        for value in sequence: insert(value)
    for name, kind, variable in symbols:
        if kind == 'env':
            if variable != 'CFG_RELEASE': raise ValueError(f"unsupported environment variable: {variable}")
            index = indices[release] if release in indices else insert(release)
            named.append(('sym', name, index))
    return values, named, bases


def go_string(text):
    # JSON string escapes are valid Go except escaped slash (not emitted), and
    # JSON's UTF16 surrogate escapes (avoid those with ensure_ascii=False).
    return json.dumps(text, ensure_ascii=False).replace('\\u0000', '\\x00')


def generate(source, release):
    values, named, bases = definitions(source, release)
    lines = [
        '// Code generated by tools/port-rust-symbol/generate_predefined.py; DO NOT EDIT.',
        '// SPDX-License-Identifier: MIT OR Apache-2.0',
        '// Source: compiler/rustc_span/src/symbol.rs at 2d20b42b883dcfc014f3c2c56081eeb6091c2179.',
        '// Macro order: keywords, ordinary symbols, digits, ASCII letters, tracked environment symbols.',
        'package rustcspan', '',
        f'const SymbolCFGRelease = {go_string(release)}',
        f'const PredefinedSymbolsCount uint32 = {len(values)}',
        f'const symbolDigitsBase uint32 = {bases[0]}',
        f'const symbolUppercaseLettersBase uint32 = {bases[1]}',
        f'const symbolLowercaseLettersBase uint32 = {bases[2]}', '',
        'var predefinedSymbolStrings = [...]string{',
    ]
    lines.extend(f'\t{go_string(value)}, // {index}' for index, value in enumerate(values))
    lines.extend(['}', '', '// Each getter preserves an immutable source constant. The underscore in',
                  '// Sym_<name> preserves case-distinct Rust symbol identifiers without collisions.'])
    for group, name, index in named:
        go_name = 'Kw' + name if group == 'kw' else 'Sym_' + name
        lines.append(f'func {go_name}() Symbol {{ return Symbol{{value: {index}}} }}')
    lines.extend(['', '// PredefinedSymbolNamed looks up an exact macro identifier, including its module.',
                  'func PredefinedSymbolNamed(name string) (Symbol, bool) {', '\tswitch name {'])
    for group, name, index in named:
        lines.append(f'\tcase "{group}::{name}": return Symbol{{value: {index}}}, true')
    lines.extend(['\tdefault: return Symbol{}, false', '\t}', '}', ''])
    return '\n'.join(lines).encode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--cfg-release', default='1.101.0')
    parser.add_argument('--output', type=Path, default=TARGET)
    local_go = ROOT / '.toolchain/go/bin/go'
    parser.add_argument('--go', default=os.environ.get('FERRUGO_GO',str(local_go) if local_go.exists() else 'go'))
    args = parser.parse_args()
    original = native_profile.source_bytes('compiler/rustc_span/src/symbol.rs')
    if hashlib.sha256(original).hexdigest() != SOURCE_SHA256: raise SystemExit('symbol source checksum mismatch')
    data = generate(original.decode(), args.cfg_release)
    import tempfile
    with tempfile.TemporaryDirectory(prefix='symbol-generated-') as directory:
        temp = Path(directory) / 'generated.go'; temp.write_bytes(data)
        # gofmt lives beside the selected Go executable; generation never uses
        # the system's unrelated application named /usr/bin/go.
        import shutil
        executable = Path(shutil.which(args.go) or args.go).resolve()
        formatter = executable.parent / 'gofmt'
        subprocess.run([str(formatter), '-w', str(temp)], check=True)
        data = temp.read_bytes()
    if args.check:
        if not args.output.exists() or args.output.read_bytes() != data: raise SystemExit(f'{args.output} differs')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True); args.output.write_bytes(data)
    print(json.dumps({'cfg_release': args.cfg_release, 'predefined': len(definitions(original.decode(), args.cfg_release)[0]), 'sha256': hashlib.sha256(data).hexdigest()}))


if __name__ == '__main__': main()
