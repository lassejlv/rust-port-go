// Command char-unicode generates the exact Rust standard-library character
// predicates used by the parse-format source port. Production does not run Rust.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func main() {
	compiler := os.Getenv("FERRUGO_RUSTC")
	if compiler == "" {
		compiler = ".toolchain/rust/bin/rustc"
	}
	root := flag.String("root", ".", "repository root")
	rustc := flag.String("rustc", compiler, "Rust compiler name/path")
	check := flag.Bool("check", false, "verify generated files")
	flag.Parse()
	if err := run(*root, *rustc, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func digest(data []byte) string { sum := sha256.Sum256(data); return hex.EncodeToString(sum[:]) }
func run(root, compiler string, check bool) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	if !filepath.IsAbs(compiler) {
		if strings.ContainsAny(compiler, "/\\") {
			compiler = filepath.Join(root, compiler)
		} else {
			compiler, err = exec.LookPath(compiler)
			if err != nil {
				return err
			}
		}
	}
	version, err := exec.Command(compiler, "--version").Output()
	if err != nil {
		return err
	}
	if strings.TrimSpace(string(version)) != "rustc 1.99.1 (58cf8f9c3 2026-10-13)" {
		return fmt.Errorf("expected pinned Rust 1.99.1, found %s", version)
	}
	tool := filepath.Join(root, "tools", "port-rust-parse-format", "char-unicode")
	source := filepath.Join(tool, "oracle.rs")
	sourceBytes, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	temp, err := os.MkdirTemp("", "parse-format-char-oracle-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(temp)
	binary := filepath.Join(temp, "oracle")
	if output, err := exec.Command(compiler, "--edition=2024", "-C", "opt-level=2", source, "-o", binary).CombinedOutput(); err != nil {
		return fmt.Errorf("compile character oracle: %w\n%s", err, output)
	}
	raw, err := exec.Command(binary).Output()
	if err != nil {
		return err
	}
	if len(raw) != 9+0x110000 || string(raw[:9]) != "PFCU2\x00\x11\x00\x00" {
		return fmt.Errorf("invalid character oracle stream")
	}
	flags := raw[9:]
	var table bytes.Buffer
	fmt.Fprintln(&table, "// BEGIN GENERATED RUST CHARACTER TABLES")
	fmt.Fprintln(&table, "// Rust 1.99.1 / Unicode 17.0.0; generated by tools/port-rust-parse-format/char-unicode.")
	counts := []int{0, 0}
	for group, item := range []struct {
		name string
		mask byte
	}{{"escapedUnicodeRanges", 1}, {"nonInitialEscapedUnicodeRanges", 4}} {
		if group == 1 {
			identical := true
			for _, flag := range flags {
				if (flag&1 != 0) != (flag&4 != 0) {
					identical = false
					break
				}
			}
			if identical {
				counts[1] = counts[0]
				fmt.Fprintln(&table, "var nonInitialEscapedUnicodeRanges = escapedUnicodeRanges")
				continue
			}
		}
		fmt.Fprintf(&table, "var %s = [][2]rune{\n", item.name)
		for i := 0; i < len(flags); i++ {
			if flags[i]&item.mask == 0 {
				continue
			}
			first := i
			for i+1 < len(flags) && flags[i+1]&item.mask != 0 {
				i++
			}
			fmt.Fprintf(&table, "{0x%x,0x%x},\n", first, i)
			counts[group]++
		}
		fmt.Fprintln(&table, "}")
	}
	fmt.Fprintln(&table, "// END GENERATED RUST CHARACTER TABLES")
	libPath := filepath.Join(root, "port", "rust", "compiler", "rustc_parse_format", "src", "lib.go")
	lib, err := os.ReadFile(libPath)
	if err != nil {
		return err
	}
	begin := bytes.Index(lib, []byte("// BEGIN GENERATED RUST CHARACTER TABLES"))
	end := bytes.Index(lib, []byte("// END GENERATED RUST CHARACTER TABLES"))
	if begin < 0 || end < begin {
		return fmt.Errorf("character table markers missing")
	}
	end += len("// END GENERATED RUST CHARACTER TABLES")
	updated := append(append(append([]byte{}, lib[:begin]...), table.Bytes()...), lib[end:]...)
	updated, err = format.Source(updated)
	if err != nil {
		return err
	}
	fixturePath := filepath.Join(tool, "oracle.bin.gz")
	fixture, err := oracleFixture(fixturePath, raw, check)
	if err != nil {
		return err
	}
	manifest, err := json.MarshalIndent(struct {
		Rustc        string   `json:"rustc"`
		Unicode      [3]uint8 `json:"unicode"`
		ScalarValues int      `json:"scalar_values"`
		Ranges       int      `json:"escaped_unicode_ranges"`
		StringRanges int      `json:"non_initial_string_escape_ranges"`
		OracleSource string   `json:"oracle_source_sha256"`
		Raw          string   `json:"raw_sha256"`
		Compressed   string   `json:"compressed_sha256"`
	}{strings.TrimSpace(string(version)), [3]uint8{17, 0, 0}, 0x110000 - 0x800, counts[0], counts[1], digest(sourceBytes), digest(raw), digest(fixture)}, "", "  ")
	if err != nil {
		return err
	}
	manifest = append(manifest, '\n')
	for path, data := range map[string][]byte{libPath: updated, fixturePath: fixture, filepath.Join(tool, "manifest.json"): manifest} {
		if check {
			existing, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(existing, data) {
				return fmt.Errorf("generated file differs: %s", path)
			}
		} else {
			if err := os.WriteFile(path, data, 0644); err != nil {
				return err
			}
		}
	}
	fmt.Printf("verified/generated %d Rust character and %d string Debug escape ranges across all Unicode scalars\n", counts[0], counts[1])
	return nil
}
func oracleFixture(path string, raw []byte, check bool) ([]byte, error) {
	existing, err := os.ReadFile(path)
	if err == nil {
		reader, e := gzip.NewReader(bytes.NewReader(existing))
		if e == nil {
			decoded, readErr := io.ReadAll(io.LimitReader(reader, int64(len(raw))+1))
			closeErr := reader.Close()
			if readErr == nil && closeErr == nil && bytes.Equal(decoded, raw) {
				return existing, nil
			}
		}
		if check {
			return nil, fmt.Errorf("invalid character fixture")
		}
	} else if !os.IsNotExist(err) || check {
		return nil, err
	}
	var output bytes.Buffer
	writer, err := gzip.NewWriterLevel(&output, gzip.BestCompression)
	if err != nil {
		return nil, err
	}
	if _, err := writer.Write(raw); err != nil {
		return nil, err
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}
