#!/usr/bin/env python3
"""Verify and reproduce the exact used UnicodeWidthChar::width scalar domain."""
import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SHA = "b4ac048d71ede7ee76d585517add45da530660ef4390e49b098733c6e897f254"
PREFIX = "unicode-width-0.2.2/"
TARGET = Path("port/dependencies/unicode-width/v0_2_2")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def tool(name, root):
    if not name:
        raise SystemExit("empty compiler selection")
    candidate = root / name if "/" in name else shutil.which(name)
    if not candidate or not os.access(candidate, os.X_OK):
        raise SystemExit("unavailable compiler: " + name)
    # Preserve argv[0] dispatch for rustup's rustc symlink; resolving it would
    # execute rustup under the wrong command name.
    return os.path.abspath(candidate)


def run(args):
    p = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=120)
    if p.returncode:
        raise SystemExit(f"command failed: {args}\n{p.stderr.decode(errors='replace')}")
    return p.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--rustc")
    parser.add_argument("--check", action="store_true")
    q = parser.parse_args()
    root = q.root.resolve()
    selection = q.rustc if q.rustc is not None else os.environ.get("FERRUGO_RUSTC")
    if selection is None:
        selection = ".toolchain/rust/bin/rustc" if (root / ".toolchain/rust/bin/rustc").exists() else "rustc"
    compiler = tool(selection, root)
    if q.archive is not None:
        archive = q.archive.resolve()
    else:
        candidates = sorted((root / ".toolchain/port-cargo-home/registry/cache").glob("*/unicode-width-0.2.2.crate"))
        if not candidates:
            raise SystemExit("exact unicode-width archive unavailable; pass --archive")
        archive = candidates[0]
    data = archive.read_bytes()
    if digest(data) != SHA:
        raise SystemExit("unicode-width archive checksum differs")
    members = {}
    with tarfile.open(fileobj=io.BytesIO(data)) as source:
        for member in source:
            if not member.isfile() or not member.name.startswith(PREFIX):
                raise SystemExit("unexpected archive member: " + member.name)
            name = member.name[len(PREFIX):]
            if not name or name.startswith("/") or ".." in Path(name).parts or name in members:
                raise SystemExit("invalid/duplicate archive member: " + name)
            members[name] = source.extractfile(member).read()
    if len(members) != 15:
        raise SystemExit("archive member count differs")
    cache = root / ".toolchain/oracles/unicode-width-scalar"
    original = cache / "unicode-width-0.2.2"
    for name, contents in members.items():
        path = original / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(contents)
    library = cache / "libunicode_width.rlib"
    run([compiler, "--edition=2021", "--crate-type=rlib", "--crate-name=unicode_width", "--cfg", 'feature="cjk"', str(original / "src/lib.rs"), "-o", str(library)])
    binary = cache / "scalar-oracle"
    run([compiler, "--edition=2021", str(HERE / "oracle.rs"), "--extern", "unicode_width=" + str(library), "-o", str(binary)])
    values = run([str(binary)])
    if len(values) != 7 + 0x110000 or values[:7] != b"UWC1\x11\0\0":
        raise SystemExit("unexpected original scalar response")
    entries = []
    raw = values[7:]
    start = 0
    for at in range(1, len(raw) + 1):
        if at != len(raw) and raw[at] == raw[start]:
            continue
        code = raw[start]
        if code not in (0, 1, 2, 3, 4, 255):
            raise SystemExit("unexpected width code")
        if code not in (2, 255):
            entries.append((start, at - 1, code))
        start = at
    table = "// Code generated by tools/port-unicode-width-scalar; DO NOT EDIT.\n// SPDX-License-Identifier: MIT OR Apache-2.0\n// Exact unicode-width 0.2.2 UnicodeWidthChar::width results; scalar scope only.\npackage unicodewidth\n\nvar scalarRanges = [...][3]uint32{\n"
    table += "".join(f"\t{{0x{lo:06x}, 0x{hi:06x}, {code}}},\n" for lo, hi, code in entries)
    table += "}\n"
    generated = {"src/scalar_tables.go": table.encode()}
    fixture = root / TARGET / "src/testdata/scalars.bin.gz"
    compressed = None
    if fixture.exists():
        existing = fixture.read_bytes()
        try:
            if gzip.decompress(existing) == values:
                compressed = existing
        except (OSError, EOFError):
            pass
    if q.check and compressed is None:
        raise SystemExit("scalar native fixture missing, corrupt or changed")
    generated["src/testdata/scalars.bin.gz"] = compressed if compressed is not None else gzip.compress(values, compresslevel=9, mtime=0)
    for name in ["COPYRIGHT", "LICENSE-APACHE", "LICENSE-MIT"]:
        generated[name] = members[name]
    for name in [".cargo_vcs_info.json", ".gitignore", "Cargo.toml", "Cargo.toml.orig", "Cargo.lock", "README.md"]:
        generated["upstream/" + ("gitignore.source" if name == ".gitignore" else name)] = members[name]
    inventory = [{"path": name, "bytes": len(contents), "lines": contents.count(b"\n"), "sha256": digest(contents), "scope": "unported source" if name.endswith(".rs") else "archive member"} for name, contents in sorted(members.items())]
    manifest = {"crate": "unicode-width", "version": "0.2.2", "archive_sha256": SHA, "revision": json.loads(members[".cargo_vcs_info.json"])["git"]["sha1"], "unicode_version": [17, 0, 0], "scope": "Only UnicodeWidthChar::width for char, default cjk-enabled crate profile. No whole source file, UnicodeWidthStr, CJK width, tests or benchmark completion credit.", "scalar_values": 1112064, "ranges": len(entries), "compiler": run([compiler, "-vV"]).decode().strip(), "files": inventory, "response_sha256": digest(values), "fixture_sha256": digest(generated["src/testdata/scalars.bin.gz"]), "table_sha256": digest(table.encode()), "generator_sha256": digest(Path(__file__).read_bytes()), "oracle_sha256": digest((HERE / "oracle.rs").read_bytes())}
    generated["source-manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    for name, contents in generated.items():
        path = root / TARGET / name
        if q.check:
            if not path.exists() or path.read_bytes() != contents:
                raise SystemExit("generated evidence differs: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
    print(f"unicode-width0.2.2 scalar-only adapter:1112064 exact scalars,{len(entries)} ranges; all15 archive members verified")


if __name__ == "__main__":
    main()
