"""Regenerate only the scoped SDK Windows io::ErrorKind dispatch.

This is not a port of a standard-library or windows-sys source file. The
official SDK source archive is verified through the existing ruststr helper;
the SDK's generated Win32 constants are independently cross-checked against
the exact root-lockfile windows-sys archive, without trusting its extraction.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import tarfile
import tomllib

ROOT = Path(__file__).absolute().parents[2]
HERE = Path(__file__).absolute().parent
DEST = ROOT / 'port/rust/compiler/rustc_span/src/source_map_io_windows_kind.go'
PREFIX = 'rust-src-nightly/rust-src/lib/rustlib/src/rust/'
SOURCE_NAMES = ['library/std/src/sys/io/error/windows.rs',
                'library/std/src/sys/pal/windows/c/windows_sys.rs']

def sha(data):
    return hashlib.sha256(data).hexdigest()

def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result

def generate():
    helper = module('ferrugo_windows_kind_sdk', ROOT / 'tools/port-rust-str/prepare.py')
    sdk, cache = helper.verified()
    sources = {}
    with tarfile.open(cache / 'rust-src-nightly.tar.xz', 'r:xz') as archive:
        for name in SOURCE_NAMES:
            sources[name] = archive.extractfile(PREFIX + name).read()
    constants = {}
    for name, value in re.findall(r'pub const (\w+):[^=]+?=\s*(0x[0-9a-fA-F]+|[0-9]+)(?:u32|i32)?;', sources[SOURCE_NAMES[1]].decode()):
        constants[name] = int(value, 0)
    source = sources[SOURCE_NAMES[0]].decode()
    body = source.split('pub fn decode_error_kind(', 1)[1].split('/// Gets a detailed', 1)[0]
    arms = []
    for names, kind in re.findall(r'((?:c::\w+\s*(?:\|\s*)?)+)=>\s*(?:return\s+)?(\w+),', body):
        symbols = re.findall(r'c::(\w+)', names)
        arms.append((symbols, kind))
    if len(arms) != 46:
        raise RuntimeError('the selected SDK dispatch shape changed')
    lock = tomllib.loads((ROOT / '.toolchain/upstream-rust/Cargo.lock').read_text())
    package, = [p for p in lock['package'] if p['name'] == 'windows-sys' and p['version'] == '0.61.2']
    archives = list((ROOT / '.toolchain/port-cargo-home/registry/cache').glob('*/windows-sys-0.61.2.crate'))
    if len(archives) != 1 or sha(archives[0].read_bytes()) != package['checksum']:
        raise RuntimeError('root-lockfile windows-sys archive is missing or differs')
    registry = {}
    selected = ['src/Windows/Win32/Foundation/mod.rs', 'src/Windows/Win32/Networking/WinSock/mod.rs']
    with tarfile.open(archives[0], 'r:gz') as archive:
        for relative in selected:
            data = archive.extractfile('windows-sys-0.61.2/' + relative).read()
            registry[relative] = data
    registry_constants = {}
    for data in registry.values():
        for name, value in re.findall(r'pub const (\w+):[^=]+?=\s*(0x[0-9a-fA-F]+|[0-9]+)(?:u32|i32)?;', data.decode()):
            registry_constants[name] = int(value, 0)
    lines = ['//go:build windows', '', '// SPDX-License-Identifier: MIT OR Apache-2.0',
             '// Generated by tools/port-rust-source-map/generate_windows_kind.py.',
             '// Scoped SDK708c94 Windows decode_error_kind; locked windows-sys0.61.2',
             '// constants independently verified. No std/dependency source-file credit.',
             'package rustcspan', '', 'func sourceMapWindowsErrorKind(code int32) string {', '\tswitch uint32(code) {']
    for names, kind in arms:
        values = [constants[name] for name in names]
        if any(registry_constants.get(name) != value for name, value in zip(names, values)):
            raise RuntimeError('SDK/locked registry constant differs: ' + ','.join(names))
        lines += ['\tcase ' + ', '.join(map(str, values)) + ': // ' + ', '.join(names), '\t\treturn "' + kind + '"']
    lines += ['\tdefault:', '\t\treturn "Uncategorized"', '\t}', '}', '']
    data = '\n'.join(lines).encode()
    proof = {'schema': 1, 'scope': 'scoped Windows ErrorKind match only; no whole standard-library/dependency file credit',
             'sdk_commit': sdk['compiler_commit'], 'sdk_archive_sha256': sdk['sha256'],
             'sdk_sources': {name: {'bytes': len(data), 'sha256': sha(data)} for name, data in sources.items()},
             'registry_package': {'name': 'windows-sys', 'version': '0.61.2', 'archive_sha256': package['checksum'],
                                  'selected_sources': {name: sha(data) for name, data in registry.items()}},
             'arms': len(arms), 'constants': sum(len(names) for names, _ in arms), 'generated_sha256': sha(data)}
    return data, (json.dumps(proof, indent=2, sort_keys=True) + '\n').encode()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, proof = generate()
    manifest = HERE / 'windows_kind_sources.json'
    if args.check:
        if DEST.read_bytes() != data or manifest.read_bytes() != proof:
            raise RuntimeError('Windows ErrorKind source/generation drift')
    else:
        DEST.write_bytes(data)
        manifest.write_bytes(proof)
    print('46 Windows ErrorKind arms verified against official SDK and locked registry archive')

if __name__ == '__main__':
    main()
